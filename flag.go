package kongusage

import (
	"fmt"

	"github.com/alecthomas/kong"
)

// Flag prints the usage spec of the CLI in KDL and exits, like [kong.VersionFlag].
//
// Declare it as a field of the root of the CLI:
//
//	type CLI struct {
//		UsageSpec kongusage.Flag
//	}
//
// The flag has the default tag help (see [Flag.Signature]),
// which the tag of the field overrides.
//
// Only the command line sets the flag, not an environment variable or a resolver:
// they are inherited by every run of the CLI,
// which would print the spec instead of doing its job.
// Add the tag `env:"-"` if using [kong.DefaultEnvars],
// otherwise help shows a variable which the flag ignores.
//
// The spec is generated by [WriteSpec] with the [Config] returned by the root of the CLI
// when it implements [ConfigProvider] or zero Config otherwise.
//
// In a mise task the shell completes paths relative to its current directory,
// while the task runs in its own directory (by default the root of the mise config),
// so the program has to resolve relative paths given by the user
// against MISE_ORIGINAL_CWD when it is set.
type Flag bool

// Signature implements [kong.Signature].
func (*Flag) Signature() string {
	return `help:"Print usage spec (KDL) and exit."`
}

// BeforeReset implements the Kong hook.
// Kong calls it before it applies defaults, environment variables and resolvers
// and checks required flags and arguments,
// so the flag works without them and despite invalid values in them.
func (*Flag) BeforeReset(app *kong.Kong, ctx *kong.Context, path *kong.Path) error {
	// Kong also calls the hook for a flag with a set environment variable,
	// and the field may keep a value of a previous parse,
	// so only a value from the command line is taken.
	value := ctx.Value(path)
	if !value.IsValid() {
		return nil
	}
	var set bool
	switch v := value.Interface().(type) {
	case Flag:
		set = bool(v)
	case *Flag:
		set = v != nil && bool(*v)
	default:
		panic(fmt.Sprintf("--%s: unexpected type %T", path.Flag.Name, v))
	}
	// Kong calls the hook for any value, e.g. --usage-spec=false.
	if !set {
		return nil
	}

	err := WriteSpec(app.Stdout, app, rootConfig(app))
	if err != nil {
		return err
	}
	app.Exit(0)
	return nil
}
